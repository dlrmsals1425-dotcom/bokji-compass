/** 알려진 서식의 해당 동의/확인 그룹만 반환한다. 반환 배열의 변경은 등록부에 영향을 주지 않는다. */
export function writingDisclosure(formId: string, groupId: string): string[] {
  const source = WRITING_DISCLOSURE_SOURCES[formId];
  const paragraphs = source?.groups?.[groupId];
  if (!Array.isArray(paragraphs)) return [];
  return [source.sourceTitle, ...paragraphs.map(paragraph => paragraph.text)];
}
